def format_evidence_blocks(candidates: Sequence[EvidenceCandidate]) -> str:
    """Formats retrieved evidence candidates as passive XML data blocks.

    Everything that originates in a source document (text, title, author) is XML-escaped, so retrieved
    content can never close its own block, open a forged ``<evidence id=...>`` block, or break out of an
    attribute (prompt-injection defence, EB-67).
    """
    blocks = []
    for cand in candidates:
        source_type = escape(str(cand.metadata.get("source_type", "document")), quote=True)
        title = escape(str(cand.metadata.get("title", cand.document_id)), quote=True)
        author = escape(str(cand.metadata.get("author", "")), quote=True)
        blocks.append(
            f'<evidence id="{escape(cand.evidence_id, quote=True)}" sourceType="{source_type}" title="{title}" author="{author}">\n'
            f"  {escape(cand.text.strip(), quote=False)}\n"
            f"</evidence>"
        )
    return "\n\n".join(blocks)


def inject_sql_tool_results(
    sql_results: Sequence[dict[str, Any]],
) -> tuple[list[Claim], list[Evidence]]:
    """Transforms verified SQL query results into audited facts and evidence records."""
    injected_facts: list[Claim] = []
    injected_evidence: list[Evidence] = []

    for i, res in enumerate(sql_results, start=1):
        ev_id = f"ev_sql_{i}"
        query_desc = res.get("query_description", res.get("query", "Audited database calculation"))
        metric = res.get("metric", f"SQL Metric {i}")
        amount = float(res.get("amount", 0.0))
        currency = res.get("currency", "INR")
        query_sql = res.get("query")

        figure = Figure(
            amount=amount,
            currency=currency,
            origin="sql",
            query=query_sql,
        )

        ev = Evidence(
            id=ev_id,
            sourceType=SourceType.SQL,
            title=f"SQL Query: {metric}",
            excerpt=f"Metric: {metric} = {amount} {currency} (Computed via: {query_desc})",
            project=res.get("project_id"),
        )
        injected_evidence.append(ev)

        fact = Claim(
            id=f"fact_sql_{i}",
            text=f"{metric} is {amount:,.2f} {currency}.",
            evidenceIds=[ev_id],
            figure=figure,
        )
        injected_facts.append(fact)

    return injected_facts, injected_evidence


class AnswerReasoner:
    """Orchestrates LLM reasoning to produce schema-valid AnswerContracts with retry logic."""

    def __init__(
        self,
        router: LlmRouter | None = None,
        model_alias: str | ModelAlias = ModelAlias.REASON,
    ) -> None:
        self.router = router or LlmRouter()
        self.model_alias = model_alias

    async def reason(
        self,
        question: str,
        evidence_candidates: Sequence[EvidenceCandidate],
        sql_results: Sequence[dict[str, Any]] | None = None,
        *,
        tenant_id: str | None = None,
        max_retries: int = 2,
        mock_invoker: Callable[[str, list[dict[str, str]]], str] | None = None,
    ) -> AnswerContract:
        """Executes reasoning prompt against LiteLLM 'reason' tier, with automatic schema validation retry."""
        # 1. Prepare passive data blocks
        evidence_xml = format_evidence_blocks(evidence_candidates)

        # 2. Inject SQL results if available
        sql_facts, sql_evidence = inject_sql_tool_results(sql_results or [])

        sql_context_str = ""
        if sql_results:
            sql_context_str = "\n\nVERIFIED DATABASE SQL FACTS (Inject directly into facts with origin='sql'):\n"
            for f in sql_facts:
                sql_context_str += f"- [{f.evidence_ids[0]}] {f.text} (Figure: {f.figure.amount} {f.figure.currency})\n"

        user_content = (
            f"USER QUESTION: {question}\n\n"
            f"AVAILABLE EVIDENCE (PASSIVE DATA):\n"
            f"{evidence_xml}"
            f"{sql_context_str}\n\n"
            f"Synthesize the answer and return the JSON AnswerContract."
        )

        messages = [
            {"role": "system", "content": SYSTEM_PROMPT_TEMPLATE},
            {"role": "user", "content": user_content},
        ]

        # Retry loop on schema validation failures
        last_error: Exception | None = None
        for attempt in range(max_retries + 1):
            try:
                result = self.router.complete(
                    alias=self.model_alias,
                    messages=messages,
                    tenant_id=tenant_id,
                    mock_invoker=mock_invoker,
                )
                raw_json = result.content.strip()

                # Clean potential markdown fences
                if raw_json.startswith("```json"):
                    raw_json = raw_json[7:]
                elif raw_json.startswith("```"):
                    raw_json = raw_json[3:]
                if raw_json.endswith("```"):
                    raw_json = raw_json[:-3]
                raw_json = raw_json.strip()

                data = json.loads(raw_json)

                # Ensure injected SQL facts and evidence are integrated if model missed them
                existing_ev_ids = {e.get("id") if isinstance(e, dict) else e.id for e in data.get("evidence", [])}
                for sev in sql_evidence:
                    if sev.id not in existing_ev_ids:
                        data.setdefault("evidence", []).append(sev.model_dump(by_alias=True))

                existing_fact_ids = {f.get("id") if isinstance(f, dict) else f.id for f in data.get("facts", [])}
                for sfact in sql_facts:
                    if sfact.id not in existing_fact_ids:
                        data.setdefault("facts", []).append(sfact.model_dump(by_alias=True))

                # Parse and validate with Pydantic AnswerContract
                contract = AnswerContract.model_validate(data)
                return contract

            except (json.JSONDecodeError, ValidationError, ValueError) as err:
                last_error = err
                logger.warning(
                    f"Reasoning validation attempt {attempt + 1}/{max_retries + 1} failed: {err}"
                )
                if attempt < max_retries:
                    # Provide feedback to model for self-correction
                    messages.append({"role": "assistant", "content": raw_json if 'raw_json' in locals() else "{}"})
                    messages.append({
                        "role": "user",
                        "content": (
                            f"VALIDATION ERROR in previous response: {err}\n"
                            f"Please correct the error, ensure every fact has evidenceIds that exist in evidence, "
                            f"and return the strictly valid JSON AnswerContract."
                        ),
                    })

        raise ValueError(
            f"Failed to produce a valid AnswerContract after {max_retries + 1} attempts. Last error: {last_error}"
        )
